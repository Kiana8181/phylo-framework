#!/bin/sh
#
# The ports the services listen on inside the project's Docker networks.
#
# docker-compose.yml builds every URL, command and health check from one
# variable per service; each has its usual port as default. None of these ports
# is published on the host.
#
#   PHYLO_PORT_POSTGRES       5432    PHYLO_PORT_API   8000
#   PHYLO_PORT_MINIO          9000    PHYLO_PORT_WEB   3000
#   PHYLO_PORT_MINIO_CONSOLE  9001    METHOD_<NAME>_CONTAINER_PORT  8001-8004
#
# Usage:
#   scripts/ports.sh                    show the ports in effect and check them
#   scripts/ports.sh check              check only (exit 1 on a problem)
#   scripts/ports.sh randomize          store random ports for the services only
#                                       this project talks to (database, object
#                                       store, method services)
#   scripts/ports.sh randomize --all    also the API and the web server, which
#                                       the reverse proxy addresses by port
#   options: --env-file PATH   --force (randomize again; changes stored ports)
#
# Random ports are optional. The networks are private to this project, so a
# random port hides nothing from anyone who can reach them; use it when the
# server's rules ask for non-default ports. Values are written once and then
# stay: changing a port means recreating the containers, and for the API or the
# web server also changing the reverse proxy.
#
# POSIX sh + awk only (no Node/Python).

set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/.env"
ACTION="show"
ALL=0
FORCE=0
BEGIN_MARK="# >>> internal ports (generated by scripts/ports.sh randomize) >>>"
END_MARK="# <<< internal ports <<<"
LOW=20000
HIGH=39999

die() { echo "ports: $*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    show|check|randomize) ACTION="$1" ;;
    --randomize) ACTION="randomize" ;;
    --all) ALL=1 ;;
    --force) FORCE=1 ;;
    --env-file) [ $# -ge 2 ] || die "--env-file needs a path"; ENV_FILE="$2"; shift ;;
    -h|--help) sed -n '2,29p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown argument: $1 (see --help)" ;;
  esac
  shift
done

# name:variable:default:reverse-proxy(1/0)
SERVICES="
postgres:PHYLO_PORT_POSTGRES:5432:0
minio:PHYLO_PORT_MINIO:9000:0
minio-console:PHYLO_PORT_MINIO_CONSOLE:9001:0
api:PHYLO_PORT_API:8000:1
web:PHYLO_PORT_WEB:3000:1
dowser:METHOD_DOWSER_CONTAINER_PORT:8001:0
gctree:METHOD_GCTREE_CONTAINER_PORT:8002:0
brepphylo:METHOD_BREPPHYLO_CONTAINER_PORT:8003:0
clonaltree:METHOD_CLONALTREE_CONTAINER_PORT:8004:0
"

# Value of KEY in the env file (last assignment wins), without quotes.
from_env_file() {
  [ -f "$ENV_FILE" ] || return 0
  awk -v key="$1" '
    /^[[:space:]]*#/ { next }
    {
      line = $0
      sub(/^[[:space:]]*(export[[:space:]]+)?/, "", line)
      eq = index(line, "=")
      if (eq == 0) next
      k = substr(line, 1, eq - 1); gsub(/[[:space:]]/, "", k)
      if (k != key) next
      v = substr(line, eq + 1)
      sub(/[[:space:]]+#.*$/, "", v); gsub(/^[[:space:]"'\'']+|[[:space:]"'\'']+$/, "", v)
      val = v
    }
    END { if (val != "") print val }' "$ENV_FILE"
}

# The value Compose will use: the shell environment wins over the env file,
# as it does for `docker compose`.
value_of() {
  eval "shell_value=\${$1:-}"
  if [ -n "$shell_value" ]; then echo "$shell_value"; return; fi
  from_env_file "$1"
}

port_of() {  # variable default
  v="$(value_of "$1")"
  echo "${v:-$2}"
}

# Port at the end of a URL such as http://phylo-minio:9000 (empty if none).
url_port() {
  echo "$1" | sed -n 's#^[a-zA-Z][a-zA-Z0-9+.-]*://[^/:]*:\([0-9][0-9]*\).*$#\1#p'
}

show() {
  printf '  %-14s %-32s %s\n' "service" "variable" "port"
  for row in $SERVICES; do
    name="${row%%:*}"; rest="${row#*:}"; var="${rest%%:*}"; rest="${rest#*:}"; def="${rest%%:*}"; proxied="${rest#*:}"
    port="$(port_of "$var" "$def")"
    note=""
    [ "$port" = "$def" ] || note="  (default $def)"
    [ "$proxied" = "1" ] && note="$note  <- the reverse proxy connects here"
    printf '  %-14s %-32s %s%s\n' "$name" "$var" "$port" "$note"
  done
}

check() {
  problems=0
  problem() { echo "ports: $*" >&2; problems=$((problems + 1)); }
  seen=""
  for row in $SERVICES; do
    name="${row%%:*}"; rest="${row#*:}"; var="${rest%%:*}"; rest="${rest#*:}"; def="${rest%%:*}"
    port="$(port_of "$var" "$def")"
    case "$port" in
      ''|*[!0-9]*) problem "$var=$port is not a port number"; continue ;;
    esac
    # Below 1024 a process needs a privilege these containers do not have.
    if [ "$port" -lt 1024 ] || [ "$port" -gt 65535 ]; then
      problem "$var=$port is outside 1024-65535"
    fi
    eval "port_$(echo "$name" | tr '-' '_')=$port"
  done
  # Two listeners in one container cannot share a port.
  if [ "${port_minio:-}" = "${port_minio_console:-x}" ]; then
    problem "PHYLO_PORT_MINIO and PHYLO_PORT_MINIO_CONSOLE are both ${port_minio}: the object store needs two different ports"
  fi
  # An explicit URL in the env file wins over the port variable in
  # docker-compose.yml; if the two disagree the service is asked on a port it
  # does not listen on.
  explicit="$(value_of S3_ENDPOINT_URL_DOCKER)"
  if [ -n "$explicit" ]; then
    p="$(url_port "$explicit")"
    [ -z "$p" ] || [ "$p" = "${port_minio:-}" ] || \
      problem "S3_ENDPOINT_URL_DOCKER uses port $p but PHYLO_PORT_MINIO is ${port_minio:-}: change one, or remove S3_ENDPOINT_URL_DOCKER"
  fi
  for m in DOWSER GCTREE BREPPHYLO CLONALTREE; do
    explicit="$(value_of "METHOD_${m}_URL_DOCKER")"
    [ -n "$explicit" ] || continue
    p="$(url_port "$explicit")"
    eval "want=\${port_$(echo "$m" | tr 'A-Z' 'a-z'):-}"
    [ -z "$p" ] || [ "$p" = "$want" ] || \
      problem "METHOD_${m}_URL_DOCKER uses port $p but METHOD_${m}_CONTAINER_PORT is $want: change one, or remove METHOD_${m}_URL_DOCKER"
  done
  if [ "$problems" -gt 0 ]; then
    return 1
  fi
  echo "ports: consistent."
}

# One random number in LOW..HIGH from the kernel's generator.
random_port() {
  n="$(od -An -N4 -tu4 /dev/urandom | tr -d ' \n')"
  echo $(( LOW + n % (HIGH - LOW + 1) ))
}

randomize() {
  [ -f "$ENV_FILE" ] || die "$ENV_FILE not found (copy .env.example to .env first)"
  if grep -qF "$BEGIN_MARK" "$ENV_FILE" && [ "$FORCE" -ne 1 ]; then
    echo "ports: $ENV_FILE already holds generated ports; they are kept." >&2
    echo "ports: use --force to generate new ones (the containers must then be recreated)." >&2
    show
    return 0
  fi

  chosen=""
  block=""
  proxied_changed=0
  for row in $SERVICES; do
    name="${row%%:*}"; rest="${row#*:}"; var="${rest%%:*}"; rest="${rest#*:}"; proxied="${rest#*:}"
    if [ "$proxied" = "1" ] && [ "$ALL" -ne 1 ]; then continue; fi
    while :; do
      port="$(random_port)"
      case " $chosen " in *" $port "*) continue ;; esac
      break
    done
    chosen="$chosen $port"
    block="$block$var=$port
"
    [ "$proxied" = "1" ] && proxied_changed=1
    # Keep the explicit URLs some env files carry in step with the new port.
    case "$var" in
      PHYLO_PORT_MINIO) block="${block}S3_ENDPOINT_URL_DOCKER=http://phylo-minio:$port
" ;;
      METHOD_*_CONTAINER_PORT) block="${block}${var%_CONTAINER_PORT}_URL_DOCKER=http://phylo-$name:$port
" ;;
    esac
  done

  # Earlier assignments of the same variables would be overridden anyway (the
  # last one wins); they are commented out so the file says one thing only.
  keys="$(printf '%s' "$block" | sed 's/=.*//' | tr '\n' ' ')"
  tmp="$ENV_FILE.ports.$$"
  awk -v b="$BEGIN_MARK" -v e="$END_MARK" -v keys="$keys" '
    BEGIN { n = split(keys, list, " "); for (i = 1; i <= n; i++) managed[list[i]] = 1 }
    $0 == b { skip = 1; next }
    $0 == e { skip = 0; next }
    skip { next }
    {
      line = $0
      probe = line; sub(/^[[:space:]]*(export[[:space:]]+)?/, "", probe)
      eq = index(probe, "=")
      if (eq > 0 && probe !~ /^#/) {
        k = substr(probe, 1, eq - 1); gsub(/[[:space:]]/, "", k)
        if (k in managed) line = "# (replaced by scripts/ports.sh) " line
      }
      lines[++count] = line
    }
    END { while (count > 0 && lines[count] ~ /^[[:space:]]*$/) count--; for (i = 1; i <= count; i++) print lines[i] }
  ' "$ENV_FILE" > "$tmp"
  { echo; echo "$BEGIN_MARK"; printf '%s' "$block"; echo "$END_MARK"; } >> "$tmp"
  # The file keeps its permissions and owner (cat, not mv).
  cat "$tmp" > "$ENV_FILE"
  rm -f "$tmp"

  echo "ports: stored in $ENV_FILE:"
  show
  echo
  echo "  Recreate the containers to apply:  docker compose --profile prod up -d"
  if [ "$proxied_changed" -eq 1 ]; then
    echo "  The reverse proxy must now send requests to phylo-api-prod:$(port_of PHYLO_PORT_API 8000)"
    echo "  and phylo-web-prod:$(port_of PHYLO_PORT_WEB 3000). Until it does, the site is unreachable."
  fi
}

case "$ACTION" in
  show) show; echo; check ;;
  check) check ;;
  randomize) randomize; check >/dev/null ;;
esac
