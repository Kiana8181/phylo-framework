#!/bin/sh
#
# Turn one global resource budget into per-container limits.
#
# Phylo-Framework runs on a shared server, so the whole stack gets one budget:
#
#   PHYLO_CPU_BUDGET         CPU cores the stack may use        (default 4)
#   PHYLO_MEMORY_BUDGET_MB   RAM in MiB the stack may use       (default 8192)
#   PHYLO_PIDS_BUDGET        processes + threads, all containers (default 4096)
#   PHYLO_RESOURCE_MODE      strict (default) | pooled
#
# Docker Compose cannot share one dynamic pool between containers: each
# container only has its own cap, read when Compose starts it. This script
# therefore splits the budget into a cap per container and writes the result as
# PHYLO_CPUS_*, PHYLO_MEM_*, PHYLO_PIDS_* variables that docker-compose.yml uses.
#
#   strict  The caps add up to at most the budget, so the stack can never exceed
#           it even when every container is busy at once. Each method service
#           gets only its own slice of the CPU budget.
#   pooled  CPU only: every method service may use the whole method share.
#           Their CPU caps then add up to MORE than the budget, so use this mode
#           only when the host enforces the total through a parent cgroup
#           (PHYLO_CGROUP_PARENT, see docs/DEPLOYMENT.md). Memory and process
#           limits are always split strictly.
#
# Usage:
#   scripts/resource-plan.sh                 show the plan for the budget in .env
#   scripts/resource-plan.sh --write         also store it in .env (managed block)
#   scripts/resource-plan.sh --check         fail if .env holds a different plan
#   scripts/resource-plan.sh --env           print KEY=VALUE lines only
#   options: --cpus N  --memory-mb N  --pids N  --mode strict|pooled  --env-file PATH
#
# Budget values are looked up in this order: command-line option, environment
# variable, the env file, built-in default. POSIX sh + awk only (no Node/Python).
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/.env"
ACTION="show"
OPT_CPUS="" ; OPT_MEM="" ; OPT_PIDS="" ; OPT_MODE=""

BEGIN_MARK="# >>> resource plan (generated by scripts/resource-plan.sh - do not edit) >>>"
END_MARK="# <<< resource plan <<<"

die() { echo "resource-plan: $*" >&2; exit 2; }

while [ $# -gt 0 ]; do
  case "$1" in
    --write) ACTION="write" ;;
    --check) ACTION="check" ;;
    --env) ACTION="env" ;;
    --cpus) [ $# -ge 2 ] || die "--cpus needs a value"; OPT_CPUS="$2"; shift ;;
    --memory-mb) [ $# -ge 2 ] || die "--memory-mb needs a value"; OPT_MEM="$2"; shift ;;
    --pids) [ $# -ge 2 ] || die "--pids needs a value"; OPT_PIDS="$2"; shift ;;
    --mode) [ $# -ge 2 ] || die "--mode needs a value"; OPT_MODE="$2"; shift ;;
    --env-file) [ $# -ge 2 ] || die "--env-file needs a value"; ENV_FILE="$2"; shift ;;
    -h|--help) sed -n '2,36p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option: $1 (try --help)" ;;
  esac
  shift
done

# Value of KEY in the env file, outside the generated block (last one wins).
from_env_file() {
  [ -f "$ENV_FILE" ] || return 0
  awk -v key="$1" -v b="$BEGIN_MARK" -v e="$END_MARK" '
    $0 == b { skip = 1; next }
    $0 == e { skip = 0; next }
    skip { next }
    /^[[:space:]]*#/ { next }
    {
      line = $0
      sub(/^[[:space:]]*(export[[:space:]]+)?/, "", line)
      eq = index(line, "=")
      if (eq == 0) next
      k = substr(line, 1, eq - 1); gsub(/[[:space:]]/, "", k)
      if (k != key) next
      v = substr(line, eq + 1)
      sub(/[[:space:]]+#.*$/, "", v); gsub(/^[[:space:]"'\'']+|[[:space:]"'\'']+$/, "", v)
      val = v
    }
    END { if (val != "") print val }' "$ENV_FILE"
}

pick() { # option, environment value, key, default
  if [ -n "$1" ]; then echo "$1"; return; fi
  if [ -n "$2" ]; then echo "$2"; return; fi
  v="$(from_env_file "$3")"
  if [ -n "$v" ]; then echo "$v"; else echo "$4"; fi
}

CPUS="$(pick "$OPT_CPUS" "${PHYLO_CPU_BUDGET:-}" PHYLO_CPU_BUDGET 4)"
MEM="$(pick "$OPT_MEM" "${PHYLO_MEMORY_BUDGET_MB:-}" PHYLO_MEMORY_BUDGET_MB 8192)"
PIDS="$(pick "$OPT_PIDS" "${PHYLO_PIDS_BUDGET:-}" PHYLO_PIDS_BUDGET 4096)"
MODE="$(pick "$OPT_MODE" "${PHYLO_RESOURCE_MODE:-}" PHYLO_RESOURCE_MODE strict)"

case "$MODE" in strict|pooled) ;; *) die "PHYLO_RESOURCE_MODE must be 'strict' or 'pooled', got '$MODE'" ;; esac
echo "$CPUS" | grep -Eq '^[0-9]+(\.[0-9]+)?$' || die "PHYLO_CPU_BUDGET must be a number of cores, got '$CPUS'"
echo "$MEM" | grep -Eq '^[0-9]+$' || die "PHYLO_MEMORY_BUDGET_MB must be a whole number of MiB, got '$MEM'"
echo "$PIDS" | grep -Eq '^[0-9]+$' || die "PHYLO_PIDS_BUDGET must be a whole number, got '$PIDS'"

# ---------------------------------------------------------------------------
# The allocation table. One row per container:
#   name  role  cpu_floor cpu_weight  mem_floor_mb mem_weight  pids_floor pids_weight
# A container gets its floor plus a weighted part of whatever the budget leaves
# after all floors. Memory floors come from measurement (docs/DEPLOYMENT.md):
# each R service idles near 800 MiB and needs about 1.7 GiB for a single job;
# the one-shot MinIO init needs about 128 MiB to create a user (below that it
# is OOM-killed), so it gets twice that.
# ---------------------------------------------------------------------------
TABLE='
POSTGRES    infra   0.25 1.0   256 1.00  256 1
MINIO       infra   0.25 0.5   384 0.50  256 1
MINIO_INIT  infra   0.10 0.0   256 0.00   64 0
API         infra   0.25 2.0   256 0.50  128 1
WORKER      infra   0.10 0.5   192 0.25   64 1
WEB         infra   0.10 0.5   256 0.25  128 1
DOWSER      method  0.25 3.0  2048 3.00  256 2
BREPPHYLO   method  0.25 3.0  2048 3.00  256 2
GCTREE      method  0.25 3.0   512 2.00  512 2
CLONALTREE  method  0.25 3.0   384 1.50  512 2
'

PLAN="$(printf '%s\n' "$TABLE" | awk -v cpus="$CPUS" -v mem="$MEM" -v pids="$PIDS" -v mode="$MODE" '
  NF == 8 {
    n++; name[n] = $1; role[n] = $2
    cf[n] = $3; cw[n] = $4; mf[n] = $5; mw[n] = $6; pf[n] = $7; pw[n] = $8
    cfs += $3; cws += $4; mfs += $5; mws += $6; pfs += $7; pws += $8
  }
  END {
    bad = 0
    if (cpus + 0 < cfs - 1e-9) { printf "ERROR PHYLO_CPU_BUDGET=%s is below the minimum of %.2f cores\n", cpus, cfs; bad = 1 }
    if (mem + 0 < mfs)         { printf "ERROR PHYLO_MEMORY_BUDGET_MB=%s is below the minimum of %d MiB\n", mem, mfs; bad = 1 }
    if (pids + 0 < pfs)        { printf "ERROR PHYLO_PIDS_BUDGET=%s is below the minimum of %d\n", pids, pfs; bad = 1 }
    if (bad) exit 0

    crest = cpus - cfs; mrest = mem - mfs; prest = pids - pfs
    for (i = 1; i <= n; i++) {
      # Round down, so rounding can never push the total above the budget.
      c[i] = int((cf[i] + crest * cw[i] / cws) * 100 + 1e-6) / 100
      m[i] = int(mf[i] + mrest * mw[i] / mws)
      p[i] = int(pf[i] + prest * pw[i] / pws)
      if (role[i] == "method") methodcpu += c[i]
    }
    for (i = 1; i <= n; i++) {
      strictcpu += c[i]; summ += m[i]; sump += p[i]
      if (mode == "pooled" && role[i] == "method") c[i] = methodcpu
      sumc += c[i]
    }
    for (i = 1; i <= n; i++) printf "ROW %s %s %.2f %d %d\n", name[i], role[i], c[i], m[i], p[i]
    printf "SUM %.2f %d %d %.2f %.2f\n", sumc, summ, sump, strictcpu, methodcpu
  }')"

if printf '%s\n' "$PLAN" | grep -q '^ERROR '; then
  printf '%s\n' "$PLAN" | sed -n 's/^ERROR /resource-plan: /p' >&2
  echo "resource-plan: raise the budget; the minimums cover one job per method service." >&2
  exit 1
fi

env_lines() {
  echo "PHYLO_RESOURCE_PLAN_FOR=cpu=${CPUS},memory_mb=${MEM},pids=${PIDS},mode=${MODE}"
  printf '%s\n' "$PLAN" | awk '$1 == "ROW" {
    printf "PHYLO_CPUS_%s=%s\nPHYLO_MEM_%s=%dm\nPHYLO_PIDS_%s=%d\n", $2, $4, $2, $5, $2, $6
  }'
}

show_plan() {
  echo "Resource plan  (budget: ${CPUS} CPU, ${MEM} MiB, ${PIDS} PIDs; mode: ${MODE})"
  echo
  printf '  %-12s %-7s %6s %10s %6s\n' container role cpus memory pids
  printf '%s\n' "$PLAN" | awk '$1 == "ROW" { printf "  %-12s %-7s %6s %8d m %6d\n", tolower($2), $3, $4, $5, $6 }'
  printf '%s\n' "$PLAN" | awk -v cpus="$CPUS" -v mem="$MEM" -v pids="$PIDS" -v mode="$MODE" '$1 == "SUM" {
    printf "  %-12s %-7s %6s %8d m %6d\n", "total", "", $2, $3, $4
    printf "  %-12s %-7s %6s %8d m %6d\n\n", "budget", "", cpus, mem, pids
    if (mode == "pooled") {
      printf "  POOLED CPU: each method service may use the whole method share (%.2f cores).\n", $6
      printf "  The CPU caps above add up to %.2f cores, more than the budget. Only use this\n", $2
      printf "  mode with PHYLO_CGROUP_PARENT set to a host cgroup that enforces %s cores.\n", cpus
    }
  }'
}

managed_block() {
  echo "$BEGIN_MARK"
  env_lines
  echo "$END_MARK"
}

current_block() {
  [ -f "$ENV_FILE" ] || return 0
  awk -v b="$BEGIN_MARK" -v e="$END_MARK" '$0 == b { on = 1 } on { print } $0 == e { on = 0 }' "$ENV_FILE"
}

case "$ACTION" in
  env)
    env_lines ;;
  show)
    show_plan
    if [ -f "$ENV_FILE" ] && [ "$(current_block)" != "$(managed_block)" ]; then
      echo "  Not stored in $ENV_FILE yet (or stored for another budget): run with --write."
    fi ;;
  check)
    if [ "$(current_block)" = "$(managed_block)" ]; then
      echo "resource-plan: $ENV_FILE matches the budget (${CPUS} CPU, ${MEM} MiB, ${PIDS} PIDs, ${MODE})."
    else
      echo "resource-plan: $ENV_FILE does not hold the plan for the configured budget." >&2
      echo "resource-plan: run scripts/resource-plan.sh --write, then recreate the containers." >&2
      exit 1
    fi ;;
  write)
    [ -f "$ENV_FILE" ] || die "$ENV_FILE not found (copy .env.example to .env first)"
    tmp="$ENV_FILE.resource-plan.$$"
    # Keep everything outside the managed block, drop trailing blank lines, then
    # append the fresh block. The file keeps its permissions (cat, not mv).
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
      $0 == b { skip = 1; next }
      $0 == e { skip = 0; next }
      skip { next }
      { lines[++n] = $0 }
      END { while (n > 0 && lines[n] ~ /^[[:space:]]*$/) n--; for (i = 1; i <= n; i++) print lines[i] }' "$ENV_FILE" > "$tmp"
    { echo; managed_block; } >> "$tmp"
    cat "$tmp" > "$ENV_FILE"
    rm -f "$tmp"
    show_plan
    echo "  Stored in $ENV_FILE. Recreate the containers to apply:"
    echo "    docker compose --profile prod up -d" ;;
esac
