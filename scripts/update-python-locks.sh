#!/usr/bin/env bash
#
# Regenerate requirements.lock for the three Python services.
#
# requirements.txt pins the packages a service asks for; requirements.lock pins
# everything pip actually installs (including indirect dependencies), so every
# image build installs the same versions that were tested and audited. The
# Dockerfiles install with `-c requirements.lock`, and CI runs pip-audit on
# these files.
#
# Each lock is resolved inside the same Python base image its Dockerfile uses,
# so no host Python is involved.
#
#   scripts/update-python-locks.sh              # keep current pins, add what is missing
#   scripts/update-python-locks.sh --upgrade    # re-resolve indirect dependencies to the newest allowed
#   scripts/update-python-locks.sh api          # one service only (api | gctree | clonaltree)
#
# After a lock changes: rebuild the image and run the tests before committing.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UPGRADE=0
SERVICES=()
for arg in "$@"; do
  case "$arg" in
    --upgrade) UPGRADE=1 ;;
    api|gctree|clonaltree) SERVICES+=("$arg") ;;
    *) echo "Unknown argument: $arg" >&2; exit 2 ;;
  esac
done
[[ ${#SERVICES[@]} -gt 0 ]] || SERVICES=(api gctree clonaltree)

service_dir(){ case "$1" in api) echo "apps/api" ;; *) echo "services/$1" ;; esac; }

# The Python image of the final (runtime) stage of each service's Dockerfile.
# `FROM ${PYTHON_IMAGE}` is resolved through the matching `ARG PYTHON_IMAGE=`.
service_image(){
  local dockerfile="$ROOT/$(service_dir "$1")/Dockerfile"
  awk '
    # Exact upper-case keywords only: Dockerfile heredocs contain Python
    # lines such as "from PyQt5 import ...".
    $1 == "ARG" && $2 ~ /^PYTHON_IMAGE=/ { sub(/^PYTHON_IMAGE=/, "", $2); arg = $2 }
    $1 == "FROM" { img = $2 }
    END { if (img == "${PYTHON_IMAGE}") img = arg; print img }' "$dockerfile"
}

for svc in "${SERVICES[@]}"; do
  dir="$(service_dir "$svc")"
  image="$(service_image "$svc")"
  echo "==> $svc ($image)"
  docker run --rm -e UPGRADE="$UPGRADE" -e SERVICE="$svc" -v "$ROOT/$dir:/work" "$image" sh -euc '
    cd /tmp
    # In the gctree image PyQt5 comes from the distribution packages, not pip
    # (see services/gctree/Dockerfile). Mirror that here so pip treats it as
    # already installed instead of trying to build it from source.
    grep -vE "^[[:space:]]*PyQt5([<>=!~].*)?$" /work/requirements.txt > requirements.txt
    if [ "$SERVICE" = "gctree" ]; then
      apt-get update -qq >/dev/null
      apt-get install -y -qq --no-install-recommends python3-pyqt5 python3-pyqt5.qtsvg python3-pyqt5.qtopengl >/dev/null
      export PYTHONPATH=/usr/lib/python3/dist-packages
    fi
    constraints=""
    if [ "$UPGRADE" != "1" ] && [ -s /work/requirements.lock ]; then
      grep -vE "^[[:space:]]*(#|$)" /work/requirements.lock > constraints.txt
      constraints="-c constraints.txt"
    fi
    python -m venv /tmp/venv
    /tmp/venv/bin/pip install --quiet --disable-pip-version-check --no-cache-dir -r requirements.txt $constraints
    {
      echo "# Generated by scripts/update-python-locks.sh - do not edit by hand."
      echo "# Full pinned dependency set for $(python -c "import sys; print(\"Python %d.%d\" % sys.version_info[:2])")."
      # --path: only what pip installed into the venv, not distribution packages.
      /tmp/venv/bin/pip freeze --disable-pip-version-check --exclude pip --exclude setuptools --exclude wheel \
        --path "$(/tmp/venv/bin/python -c "import sysconfig; print(sysconfig.get_paths()[\"purelib\"])")"
    } > /work/requirements.lock.new
    mv /work/requirements.lock.new /work/requirements.lock
  '
  echo "    wrote $dir/requirements.lock ($(grep -cvE '^(#|$)' "$ROOT/$dir/requirements.lock") packages)"
done
